// 8夜目の画面撮影：教官の机の世界の全画面を幅390×高さ844で撮る
// 使い方：npx vite を起動し、npx tsx scripts/mkshots8.ts <dir> のあと SHOTS_DIR=<dir> node scripts/ui-night8.cjs [出力先=docs/screenshots/night8]
const { chromium } = require('playwright');
const path = require('path');
const out = process.argv[2] || 'docs/screenshots/night8';
const dir = process.env.SHOTS_DIR;
const W = Number(process.env.W || 390);
(async () => {
  require('fs').mkdirSync(out, { recursive: true });
  const b = await chromium.launch();
  const p = await b.newPage({ viewport: { width: W, height: 844 }, deviceScaleFactor: Number(process.env.DPR || 2) });
  const errors = [];
  p.on('pageerror', (e) => errors.push('pageerror: ' + e.message));
  p.on('console', (m) => { if (m.type() === 'error') errors.push('console: ' + m.text()); });
  p.on('dialog', (d) => d.accept(d.type() === 'prompt' ? '1' : undefined));
  const wide = [];
  const shot = async (n, full = false) => { await p.waitForTimeout(450); const w = await p.evaluate(() => document.documentElement.scrollWidth); if (w > W) wide.push(`${n}: ${w}px`); await p.screenshot({ path: `${out}/${n}.png`, fullPage: full }); console.log('shot', n); };
  const open = async (file, keep) => {
    await p.goto('http://localhost:5173/rimina-academy/');
    await p.evaluate(() => indexedDB.deleteDatabase('rimina-academy'));
    await p.reload(); await p.waitForTimeout(500);
    await p.setInputFiles('input[type=file]', path.join(dir, file));
    await p.waitForSelector('nav.tabs, .ab-view', { timeout: 15000 }).catch(() => undefined);
    await p.waitForTimeout(700);
    if (!keep) await closeAll();
  };
  const closeAll = async () => { for (let i = 0; i < 16; i++) { const c = await p.$('.sheet button:has-text("閉じる"), .sheet button:has-text("スキップ"), .sheet button:has-text("OK"), .sheet button:has-text("丁重に断る")'); if (!c) break; await c.click(); await p.waitForTimeout(150); } };
  const click = async (sel) => { await p.click(sel).catch((e) => errors.push('click ' + sel)); await p.waitForTimeout(350); };
  const tab = async (i) => { await click(`nav.tabs button >> nth=${i}`); };
  await p.goto('http://localhost:5173/rimina-academy/'); await p.evaluate(() => indexedDB.deleteDatabase('rimina-academy')); await p.reload(); await p.waitForTimeout(600);
  await shot('00-title');
  await open('home.json');
  await shot('01-home-desk');
  await click('.desknote'); await shot('02-notebook');
  await tab(0); await click('.command'); await shot('03-today-lessons');
  await click('.lcard >> nth=1 >> .lc-head'); await shot('04-lesson-selected');
  await click('.lessonbar .btn.primary'); await p.waitForTimeout(900); await shot('05-lesson-result');
  await open('home.json');
  await tab(1); await shot('06-roster-binder');
  await click('.stucard >> nth=0'); await shot('07-detail-dossier');
  await p.evaluate(() => { const h = [...document.querySelectorAll('h3')].find((x) => x.textContent.includes('能力')); h && h.scrollIntoView(); }); await shot('08-detail-stats-growth');
  await tab(1); await click('.sectitle button:has-text("兵種試験")'); await shot('09-class-exam');
  await tab(1); await click('.sectitle button:has-text("図鑑")'); await click('.cb-grid .cb-leaf >> nth=1'); await shot('10-classbook');
  await click('.cb-node .cb-leaf >> nth=0'); await shot('11-classbook-sheet');
  await open('mentor.json');
  await click('.dn-foot span:has-text("教官")'); await shot('12-mentor');
  await p.evaluate(() => document.querySelector('.mt-branch')?.scrollIntoView()); await click('.mt-node.ready >> nth=0'); await shot('13-mentor-tree');
  await click('.mt-detail .btn.primary'); await p.waitForTimeout(600); await shot('14-mentor-learned');
  await open('news.json', true); for (let i = 0; i < 8; i++) { if (await p.$('.sheet .newspaper')) break; const c = await p.$('.sheet button:has-text("閉じる"), .sheet button:has-text("スキップ")'); if (!c) break; await c.click(); await p.waitForTimeout(200); } await shot('15-newspaper-pending', true);
  await open('home.json'); await click('.deskpaper'); await shot('16-newspaper-page');
  await open('home.json'); await click('.deskletter'); await shot('17-mail');
  await tab(2); await shot('18-war');
  await click('.pills button:has-text("敵将の名簿"), button:has-text("敵将の名簿")'); await shot('19-officers');
  await tab(3); await shot('20-yearbook');
  await tab(4); await shot('21-settings');
  await tab(0); await click('.drawer >> nth=2'); await shot('22-facilities');
  await tab(0); await click('.drawer >> nth=3'); await shot('23-armory');
  await open('board.json', true); await shot('24-quest-board');
  await open('battle.json', true); await p.waitForTimeout(800);
  for (let i = 0; i < 8; i++) await click('.bl-log');
  await shot('25-battle-report-tap');
  await click('.bl-ctrl button:has-text("速く")');
  for (let i = 0; i < 120; i++) { if (await p.$('button:has-text("結果を見る")')) break; if (await p.$('.ab-choice')) { await shot('26-battle-choice'); await p.click('.ab-copt >> nth=0'); await p.waitForTimeout(400); continue; } await p.waitForTimeout(300); }
  await click('button:has-text("結果を見る")'); await p.waitForTimeout(1000); await shot('27-battle-result');
  await open('grad.json', true); for (let i = 0; i < 8; i++) { if (await p.$('.sheet h2:has-text("進路"), .sheet h2:has-text("卒業")')) break; const c = await p.$('.sheet button:has-text("閉じる"), .sheet button:has-text("スキップ")'); if (!c) break; await c.click(); await p.waitForTimeout(200); } await shot('28-year-end');
  console.log('wide', wide.join(', ') || 'なし');
  console.log('errors', errors.join('\n') || 'なし');
  await b.close();
})();
